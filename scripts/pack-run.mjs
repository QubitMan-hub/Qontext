// Packs a recorded hardware run into src/app/ibm-run.js so the Atelier's Notary can open it without a network
// request. The raw file in data/hardware/ stays the record.
//
// Usage: node scripts/pack-run.mjs data/hardware/ibm_kingston-2026-10-12.json

import { readFileSync, writeFileSync } from 'node:fs';
import { parsePool, packPool } from '../src/engine/index.js';

const file = process.argv[2];
const packed = packPool(parsePool(readFileSync(file, 'utf8')));
const out = `// Generated by scripts/pack-run.mjs from ${file}. Do not edit by hand.\n` +
  `export const IBM_RUN = ${JSON.stringify(packed)};\n`;
writeFileSync(new URL('../src/app/ibm-run.js', import.meta.url), out);
console.log(`src/app/ibm-run.js: ${out.length} bytes`);
